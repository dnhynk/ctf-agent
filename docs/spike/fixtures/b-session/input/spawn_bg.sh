# B-3 재료 — tty의 job control 아래 백그라운드 잡을 남기고 즉시 돌아온다.
#
# 정답 경로가 아니다. §9.2가 "별도로 자식 프로세스를 만드는 명령을 포함시켜 timeout 후
# 프로세스 트리 정리(S2)를 관측한다"고 한 그 '별도로'에 해당한다. 골든 트라젝토리는
# 이것을 밟지 않는다 — 밟으면 골든 스트림이 생존자를 남기게 되고, 세션 C가 그것을
# 술어의 결함으로 오독할 수 있다. arm 프로브 B-3이 이 파일을 쓴다.
#
#   실행:  sh /input/spawn_bg.sh     (실행 비트에 의존하지 않는다)
#
# SEAM_CONTRACT §4.1-2: close 후 생존자 0이며 여기에 `&`로 띄운 백그라운드 잡이 포함된다.
# 프로세스 그룹만 정리하는 구현은 이 sleep을 남긴다.
sleep 300 &
echo "spawned background sleep pid=$!"
